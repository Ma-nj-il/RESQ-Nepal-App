-- Local/CI roles only. Production identities are provisioned outside the image with rotated secrets.
REVOKE CREATE ON SCHEMA public FROM PUBLIC;

CREATE ROLE resq_application NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
CREATE ROLE resq_worker NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
CREATE ROLE resq_outbox_relay NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;
CREATE ROLE resq_job_relay NOLOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOINHERIT NOBYPASSRLS;

CREATE ROLE resq_api LOGIN PASSWORD 'resq-api-local'
  NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT NOBYPASSRLS IN ROLE resq_application;
CREATE ROLE resq_worker_runtime LOGIN PASSWORD 'resq-worker-local'
  NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT NOBYPASSRLS IN ROLE resq_worker;
CREATE ROLE resq_outbox_runtime LOGIN PASSWORD 'resq-outbox-local'
  NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT NOBYPASSRLS IN ROLE resq_outbox_relay;
CREATE ROLE resq_job_relay_runtime LOGIN PASSWORD 'resq-job-relay-local'
  NOSUPERUSER NOCREATEDB NOCREATEROLE INHERIT NOBYPASSRLS IN ROLE resq_job_relay;

GRANT CONNECT ON DATABASE resq TO resq_api, resq_worker_runtime, resq_outbox_runtime, resq_job_relay_runtime;
